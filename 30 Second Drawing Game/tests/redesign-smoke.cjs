const a = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 1280, height: 1000}});
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.clock.install({time: new Date('2026-10-09T12:00:00Z')});await page.clock.pauseAt(new Date('2026-10-09T12:00:00Z'));
    await page.goto('file:///' + path.resolve(__dirname, '../30sDrawingGame.html').replace(/\\/g, '/'));
    a.equal(await page.locator('#configuration').evaluate(el => el.open), false);
    a.equal(await page.locator('#finish').isDisabled(), true);
    a.deepEqual(await page.locator('main > [data-region]').evaluateAll(els => els.map(el => el.dataset.region)), ['configuration', 'play', 'scoreboard', 'history']);
    await page.getByRole('button', {name: 'Dark theme', exact: true}).click();
    a.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await page.getByRole('button', {name: 'Light theme', exact: true}).click();
    await page.locator('#configuration > summary').click();
    await page.locator('#duration').fill('9');
    await page.locator('#start').click();
    a.match(await page.locator('#setupStatus').innerText(), /whole number/);
    await page.locator('#duration').fill('10');
    await page.locator('#players').fill('Ada\nBea\nCat\nDan');
    await page.locator('#configuration > summary').click();
    await page.locator('#start').click();
    a.equal(await page.locator('#finish').isDisabled(), true);
    await page.clock.runFor(12000);
    a.equal(await page.locator('#finish').isDisabled(), true);
    await page.locator('[data-winner="player-2"]').click();
    a.equal(await page.locator('#finish').isDisabled(), false);
    await page.locator('#finish').click();
    a.equal(await page.locator('#results').isVisible(), true);
    a.equal(await page.locator('#podium [data-player]').count(), 3);
    a.equal(await page.locator('#podium [data-place="1"]').getAttribute('data-player'), 'player-2');
    a.equal(await page.locator('#remainingRanks [data-player]').count(), 1);
    a.match(await page.locator('#remainingRanks').innerText(), /Dan/);
    a.equal(await page.locator('#start').isVisible(), false);
    await page.screenshot({path: path.resolve(__dirname, 'results-desktop.png'), fullPage: true, animations: 'disabled'});
    await page.setViewportSize({width: 375, height: 900});
    await page.emulateMedia({reducedMotion: 'reduce'});
    a.equal(await page.locator('#podium [data-place="1"]').evaluate(el => getComputedStyle(el).animationName), 'none');
    a.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: path.resolve(__dirname, 'results-mobile.png'), fullPage: true, animations: 'disabled'});
    await page.locator('#playAgain').click();
    a.equal(await page.locator('#results').isVisible(), false);
    a.equal(await page.locator('#history li').count(), 0);
    a.equal(await page.locator('#configuration').evaluate(el => el.open), false);
    await page.screenshot({path: path.resolve(__dirname, 'redesign-mobile.png'), fullPage: true, animations: 'disabled'});
    await page.setViewportSize({width: 1280, height: 1000});
    await page.screenshot({path: path.resolve(__dirname, 'redesign-desktop.png'), fullPage: true, animations: 'disabled'});
    await page.setViewportSize({width: 375, height: 900});
    for (const names of [['S'.repeat(40)], ['One', 'Two'], Array.from({length: 12}, (_, index) => 'Player ' + index)]) {
      await page.locator('#configuration > summary').click();
      await page.locator('#players').fill(names.join('\n'));
      await page.locator('#start').click();
      await page.clock.runFor(12000);
      await page.locator('[data-winner="none"]').click();
      await page.locator('#finish').click();
      a.equal(await page.locator('#podium [data-player]').count(), Math.min(3, names.length));
      a.equal(await page.locator('#remainingRanks [data-player]').count(), Math.max(0, names.length - 3));
      a.match(await page.locator('#resultsTitle').innerText(), /Every sketch/);
      a.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.locator('#playAgain').click();
    }
    await page.getByRole('button', {name: 'Dark theme', exact: true}).focus();
    await page.keyboard.press('Enter');
    a.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    await page.reload();
    a.equal(await page.locator('html').getAttribute('data-theme'), 'dark');
    a.equal(await page.locator('#configuration').evaluate(el => el.open), false);
    await page.screenshot({path: path.resolve(__dirname, 'redesign-dark.png'), fullPage: true, animations: 'disabled'});
    await page.locator('#configuration > summary').focus();
    await page.keyboard.press('Space');
    a.equal(await page.locator('#configuration').evaluate(el => el.open), true);
    a.deepEqual(errors, []);
    console.log('Redesign layout, themes, completion podium, ranking rows and Play again passed.');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
