const a = require('node:assert/strict');
const path = require('node:path');
const {chromium} = require(process.env.PLAYWRIGHT_PATH || 'playwright');
(async () => {
  const browser = await chromium.launch({channel: 'msedge', headless: true});
  try {
    const page = await browser.newPage({viewport: {width: 375, height: 900}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.clock.install({time: new Date('2026-10-09T12:00:00Z')});await page.clock.pauseAt(new Date('2026-10-09T12:00:00Z'));
    await page.goto('file:///' + path.resolve(__dirname, '../30sDrawingGame.html').replace(/\\/g, '/'));
    await page.locator('#configuration > summary').click();
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 150);
    await page.getByRole('button', {name: 'Edit words', exact: true}).click();
    a.equal((await page.locator('#everydayWords').inputValue()).split('\n').length, 150);
    await page.locator('#everydayWords').fill('Cup\nCar\nSpoon\nCake\nCup\n<b>Cat</b>\nहिन्दी 😀');
    await page.locator('#saveEveryday').click();
    a.match(await page.locator('#everydayFeedback').innerText(), /6 words/);
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 6);
    a.equal(await page.locator('[data-category="category-everyday"] b').count(), 0);
    await page.reload();
    await page.locator('#configuration > summary').click();
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 6);
    await page.getByRole('button', {name: 'Edit words', exact: true}).click();
    await page.locator('#everydayWords').fill('');
    await page.locator('#saveEveryday').click();
    a.match(await page.locator('#everydayFeedback').innerText(), /at least one/);
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 6);
    await page.locator('#everydayWords').fill('Cup\nSpoon');
    await page.locator('#cancelEveryday').click();
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 6);
    await page.getByRole('button', {name: 'Edit words', exact: true}).click();
    await page.locator('#everydayWords').fill('Cup\nCar');
    await page.locator('#restoreEveryday').click();
    a.equal(await page.locator('#everydayRestoreConfirm').isVisible(), true);
    await page.locator('#restoreEverydayCancel').click();
    a.equal(await page.locator('#everydayWords').inputValue(), 'Cup\nCar');
    await page.locator('#restoreEveryday').click();
    await page.locator('#restoreEverydayYes').click();
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 150);
    await page.reload();
    await page.locator('#configuration > summary').click();
    a.equal(await page.locator('[data-category="category-everyday"] input[data-prompt]').count(), 150);
    await page.locator('#selectNone').click();
    await page.getByRole('button', {name: 'Edit words', exact: true}).click();
    await page.locator('#everydayWords').fill('Cup\nCar');
    await page.locator('#saveEveryday').click();
    await page.locator('[data-category=category-everyday]').evaluate(el=>{el.open=true;});
    await page.getByRole('checkbox',{name:'Select category Everyday Things',exact:true}).check();
    await page.locator('#duration').fill('10');
    await page.locator('#start').click();
    await page.clock.runFor(2000);
    const used = await page.locator('#prompt').innerText();
    await page.locator('#configuration').evaluate(el => { el.open = true; });
    a.equal(await page.getByRole('button', {name: 'Edit words', exact: true}).isDisabled(), true);
    await page.locator('#skip').click();
    await page.getByRole('button', {name: 'Edit words', exact: true}).click();
    await page.locator('#everydayWords').fill('Cup\nCar\nSpoon');
    await page.locator('#saveEveryday').click();
    a.equal(await page.locator('#prompt').innerText(), used);
    a.match(await page.locator('#totals').innerText(), /3 selected · 2 unused/);
    await page.screenshot({path: path.resolve(__dirname, 'everyday-editor.png'), fullPage: true, animations: 'disabled'});
    a.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    a.deepEqual(errors, []);
    console.log('Everyday category editing, persistence, restore, literal labels and usage preservation passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
